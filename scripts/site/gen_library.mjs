// Generates the /library/ index pages from the PDFs that live in the repo.
// The PDFs never move; each entry links to the file on GitHub.
//
//   docs/library/reports.md  <- 资料/卖方金工研报/<series>/<file>.pdf
//   docs/library/papers.md   <- 论文/<topic>/**/<file>.pdf
//
// Both outputs are git-ignored and rebuilt by `npm run docs:dev|docs:build`.
import { writeFileSync } from 'node:fs'
import { join, basename, extname } from 'node:path'
import { ROOT, collator, walk, repoPath, githubUrl, escapeText, anchor } from './lib.mjs'

const OUT_DIR = join(ROOT, 'docs', 'library')

function group(files, depth) {
  const groups = new Map()
  for (const full of files) {
    const parts = repoPath(full)
    const key = parts.slice(depth, -1).join(' / ') || '其他'
    if (!groups.has(key)) groups.set(key, [])
    groups.get(key).push(parts)
  }
  return [...groups.entries()].sort(([a], [b]) => collator.compare(a, b))
}

function renderGroups(groups) {
  return groups
    .map(([name, items]) => {
      const lines = items
        .sort((a, b) => collator.compare(a.at(-1), b.at(-1)))
        .map((parts) => `- [${escapeText(basename(parts.at(-1), extname(parts.at(-1))).trim())}](${githubUrl('blob', parts)})`)
      return `## ${name}\n\n${items.length} 份 · [在 GitHub 打开目录](${githubUrl('tree', items[0].slice(0, -1))})\n\n${lines.join('\n')}\n`
    })
    .join('\n')
}

function writePage(file, { title, description, intro, root, depth }) {
  const pdfs = walk(join(ROOT, ...root)).filter((f) => extname(f).toLowerCase() === '.pdf')
  const groups = group(pdfs, depth)
  const toc = groups.map(([name, items]) => `- [${name}](#${anchor(name)})（${items.length}）`).join('\n')
  const body = [
    '---',
    `title: ${title}`,
    `description: ${description}`,
    'outline: false',
    '---',
    '',
    `<!-- Generated by scripts/site/gen_library.mjs. Do not edit by hand. -->`,
    '',
    `# ${title}`,
    '',
    intro,
    '',
    `共 ${pdfs.length} 份，按目录分组：`,
    '',
    toc,
    '',
    renderGroups(groups),
  ].join('\n')
  writeFileSync(join(OUT_DIR, file), body)
  return pdfs.length
}

const notice =
  '研报和论文的版权归原作者和原机构所有，这里只做学习研究用的索引，文件保存在 GitHub 仓库里。如果权利人认为某份文件不宜公开，请通过[关于页](/about#合作与联系)联系我们处理。'

const reports = writePage('reports.md', {
  title: '卖方金工研报目录',
  description: '按系列整理的卖方金融工程研报目录：华泰人工智能、华泰多因子、海通、另类交易策略、基金研究等，每份都链接到 GitHub 上的原文件。',
  intro: `按券商和系列整理的金融工程研报。${notice}`,
  root: ['资料', '卖方金工研报'],
  depth: 2,
})

const papers = writePage('papers.md', {
  title: '论文目录',
  description: '投资者情绪、行为金融学等方向的学术论文目录，按主题分组，每篇都链接到 GitHub 上的原文件。',
  intro: `按主题整理的学术论文。最新的 AI × 金融论文请看[论文雷达](/arxiv/)。${notice}`,
  root: ['论文'],
  depth: 1,
})

